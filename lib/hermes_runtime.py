"""Validated IPA operations for the first-install wizard (Python standard library)."""
import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import plistlib
import re
import shutil
import shlex
import stat
import sys
import tempfile
import urllib.parse
import urllib.request
import zipfile

OLD_GROUP = b'group.com.kamui.escape'


def group_bytes(group):
    if not re.fullmatch(r'group\.[A-Za-z0-9.-]+', group) or len(group.encode('utf-8')) != len(OLD_GROUP):
        raise ValueError('App Group must be exactly 22 ASCII characters and start with group.')
    return group.encode('ascii')


def watch_info(archive):
    candidates = []
    for name in archive.namelist():
        parts = PurePosixPath(name).parts
        if (len(parts) == 5 and parts[0] == 'Payload' and parts[1].endswith('.app')
                and parts[2] == 'Watch' and parts[3].endswith('.app') and parts[4] == 'Info.plist'):
            info = plistlib.loads(archive.read(name))
            if info.get('WKApplication') is True and info.get('CFBundleSupportedPlatforms') == ['WatchOS']:
                executable = info.get('CFBundleExecutable')
                if not executable or PurePosixPath(executable).name != executable:
                    raise ValueError('Invalid Watch executable name')
                root = name.rsplit('/', 1)[0]
                if root + '/' + executable not in archive.namelist():
                    raise ValueError('Watch executable missing')
                candidates.append((root, info))
    if len(candidates) != 1:
        raise ValueError('Expected exactly one embedded watchOS app; upstream IPA layout may have changed')
    return candidates[0]


def validate_zip(archive):
    if len(set(archive.namelist())) != len(archive.namelist()):
        raise ValueError('Duplicate archive entries')
    for entry in archive.infolist():
        parts = PurePosixPath(entry.filename).parts
        if (not parts or entry.filename.startswith('/') or '\\' in entry.filename
                or '..' in parts or ':' in parts[0]):
            raise ValueError('Invalid archive path')
        if stat.S_ISLNK(entry.external_attr >> 16):
            raise ValueError('Archive symlinks are not supported')
    bad = archive.testzip()
    if bad:
        raise ValueError('Archive CRC failure: ' + bad)


def patch(source, destination, group):
    new = group_bytes(group)
    destination = Path(destination)
    if Path(source).resolve() == destination.resolve():
        raise ValueError('Input and output IPA must be different')
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with zipfile.ZipFile(source) as zin:
            validate_zip(zin)
            root, info = watch_info(zin)
            target = root + '/' + info['CFBundleExecutable']
            count = zin.read(target).count(OLD_GROUP)
            if count == 0 and new not in zin.read(target):
                raise ValueError('Expected App Group marker missing in Watch executable; stop for upstream review')
            with tempfile.NamedTemporaryFile(dir=destination.parent, delete=False) as f:
                temporary = f.name
            total = 0
            with zipfile.ZipFile(temporary, 'w', zipfile.ZIP_DEFLATED) as zout:
                for entry in zin.infolist():
                    data = zin.read(entry.filename)
                    # The 22-byte substitution preserves Mach-O layout; signatures are regenerated by xtool.
                    if entry.filename == target or entry.filename.endswith('/HermesCompanion'):
                        total += data.count(OLD_GROUP)
                        data = data.replace(OLD_GROUP, new)
                    zout.writestr(entry, data)
            os.replace(temporary, destination)
        return {'replacements': total, 'group': group, 'watch_app': root}
    finally:
        if temporary and os.path.exists(temporary):
            os.unlink(temporary)


def extract_watch(source, destination):
    destination = Path(destination).resolve()
    if destination.exists() and any(destination.iterdir()):
        raise ValueError('Extraction destination must be empty')
    with zipfile.ZipFile(source) as archive:
        validate_zip(archive)
        root, info = watch_info(archive)
        for entry in archive.infolist():
            if not entry.filename.startswith(root + '/'):
                continue
            path = destination.joinpath(*PurePosixPath(entry.filename).parts)
            if entry.is_dir():
                path.mkdir(parents=True, exist_ok=True)
                continue
            path.parent.mkdir(parents=True, exist_ok=True)
            with archive.open(entry) as src, path.open('wb') as dst:
                shutil.copyfileobj(src, dst)
            mode = (entry.external_attr >> 16) & 0o777
            if mode:
                path.chmod(mode)
        executable = destination / root / info['CFBundleExecutable']
        executable.chmod(executable.stat().st_mode | 0o111)
    return str(destination / root)


def fetch(url):
    parsed = urllib.parse.urlparse(url)
    if parsed.scheme != 'https' or parsed.hostname not in {'api.github.com', 'github.com'}:
        raise ValueError('Unexpected release URL')
    return urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': 'HermesWatchInstaller'}), timeout=45)


def latest(destination):
    with fetch('https://api.github.com/repos/pookjw/HermesEnabler/releases/latest') as response:
        release = json.load(response)
    assets = [a for a in release.get('assets', []) if a.get('name', '').lower().endswith('.ipa')]
    if len(assets) != 1:
        raise ValueError('Expected exactly one IPA in latest upstream release')
    asset = assets[0]
    destination = Path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=destination.parent, delete=False) as out:
            temporary = out.name
            with fetch(asset['browser_download_url']) as response:
                shutil.copyfileobj(response, out)
        data_hash = hashlib.sha256(Path(temporary).read_bytes()).hexdigest()
        if asset.get('size') != Path(temporary).stat().st_size:
            raise ValueError('Downloaded IPA size differs from release metadata')
        digest = asset.get('digest')
        if digest and digest != 'sha256:' + data_hash:
            raise ValueError('Downloaded IPA SHA-256 differs from release metadata')
        with zipfile.ZipFile(temporary) as archive:
            validate_zip(archive)
            watch_info(archive)
        os.replace(temporary, destination)
        return {'tag': release['tag_name'], 'url': asset['browser_download_url'], 'sha256': data_hash}
    finally:
        if temporary and os.path.exists(temporary):
            os.unlink(temporary)


CONFIG_KEYS = ('GROUP_ID', 'WATCH_UDID', 'APP_NAME', 'LAST_IPA_URL',
               'SIGNED_IPA', 'GROUPED_IPA', 'UPSTREAM_TAG', 'LAST_SUCCESS_AT')


def checked_path(value):
    text = os.fspath(value)
    if any(c in text for c in ('\0', '\n', '\r')):
        raise ValueError('Path contains NUL or newline')
    return Path(text)


def config_read(source):
    """Parse static shell assignments only; never evaluate a shell program."""
    values = {}
    text = checked_path(source).read_text(encoding='utf-8')
    if '\0' in text:
        raise ValueError('Configuration contains NUL')
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        if '$' in line or '`' in line or line.rstrip().endswith('\\'):
            raise ValueError('Shell expansion or continuation in configuration')
        match = re.match(r'^\s*([A-Z_][A-Z_0-9]*)=(.*)$', line)
        if not match or match[1] not in CONFIG_KEYS:
            raise ValueError('Expected allowlisted static KEY=VALUE assignment')
        lexer = shlex.shlex(line.strip(), posix=True, punctuation_chars=';&|()<>~*?[]{}')
        lexer.whitespace_split = True
        tokens = list(lexer)
        if len(tokens) != 1 or not tokens[0].startswith(match[1] + '='):
            raise ValueError('Expected one static assignment per line')
        key, value = tokens[0].split('=', 1)
        if any(c in value for c in ('\0', '\n', '\r')):
            raise ValueError('Configuration value contains NUL or newline')
        values[key] = value
    group_bytes(values.get('GROUP_ID', ''))
    return {'values': values}


def _watch_profile(archive, root):
    """Extract the XML plist from raw XML or CMS; no CMS signature verification."""
    data = archive.read(root + '/embedded.mobileprovision')
    start = data.find(b'<?xml')
    end = data.find(b'</plist>', max(start, 0))
    if start < 0 or end < start:
        raise ValueError('Provisioning profile XML missing')
    result = plistlib.loads(data[start:end + len(b'</plist>')])
    if not isinstance(result, dict):
        raise ValueError('Invalid provisioning profile dictionary')
    return result


def _profile_groups(data):
    entitlements = data.get('Entitlements', {})
    if not isinstance(entitlements, dict):
        raise ValueError('Invalid profile entitlements')
    groups = entitlements.get('com.apple.security.application-groups', [])
    if not isinstance(groups, list) or any(not isinstance(g, str) for g in groups):
        raise ValueError('Invalid profile application groups')
    return groups


def profile(source):
    with zipfile.ZipFile(source) as archive:
        root, _ = watch_info(archive)
        info = _watch_profile(archive, root)
        return {'created': str(info.get('CreationDate')), 'expires': str(info.get('ExpirationDate')),
                'groups': _profile_groups(info)}


def info(source):
    with zipfile.ZipFile(checked_path(source)) as archive:
        validate_zip(archive)
        _, metadata = watch_info(archive)
        return {'bundle_id': metadata.get('CFBundleIdentifier', ''),
                'version': metadata.get('CFBundleShortVersionString', ''),
                'build': metadata.get('CFBundleVersion', '')}


def verify_grouped(source, group):
    marker = group_bytes(group)
    with zipfile.ZipFile(checked_path(source)) as archive:
        validate_zip(archive)
        root, metadata = watch_info(archive)
        if marker not in archive.read(root + '/' + metadata['CFBundleExecutable']):
            raise ValueError('Requested App Group missing in Watch executable')
        return {'group': group, 'watch_app': root}


def verify_signed(source, group, watchudid):
    """Validate profile structure and claims, not CMS or application signatures."""
    verify_grouped(source, group)
    if not watchudid or any(c in watchudid for c in ('\0', '\n', '\r')):
        raise ValueError('Watch UDID is required')
    with zipfile.ZipFile(checked_path(source)) as archive:
        validate_zip(archive)
        root, metadata = watch_info(archive)
        data = _watch_profile(archive, root)
    if group not in _profile_groups(data):
        raise ValueError('Requested App Group missing in Watch profile')
    bundle_id = metadata.get('CFBundleIdentifier')
    application_id = data.get('Entitlements', {}).get('application-identifier')
    if (not isinstance(bundle_id, str) or not bundle_id
            or not isinstance(application_id, str)
            or not application_id.endswith('.' + bundle_id)
            or not re.fullmatch(r'[A-Za-z0-9]+', application_id[:-(len(bundle_id) + 1)])):
        raise ValueError('Profile application-identifier does not match Watch bundle ID and team')
    profile_uuid = data.get('UUID')
    if not isinstance(profile_uuid, str) or not profile_uuid.strip():
        raise ValueError('Profile UUID missing or invalid')
    devices = data.get('ProvisionedDevices')
    if not isinstance(devices, list) or watchudid not in devices:
        raise ValueError('Watch UDID missing in provisioning profile')
    dates = []
    for key in ('CreationDate', 'ExpirationDate'):
        date = data.get(key)
        if not isinstance(date, datetime):
            raise ValueError('Profile date missing or invalid: ' + key)
        dates.append(date.replace(tzinfo=timezone.utc) if date.tzinfo is None else date.astimezone(timezone.utc))
    created, expires = dates
    now = datetime.now(timezone.utc)
    if not created <= now < expires:
        raise ValueError('Provisioning profile is expired or not yet valid')
    return {'created': created.isoformat(), 'expires': expires.isoformat(),
            'remaining_hours': (expires - now).total_seconds() / 3600,
            'bundle_id': metadata.get('CFBundleIdentifier', ''),
            'profile_uuid': profile_uuid,
            'validation': 'structure-only', 'cms_signature_verified': False}


def config_import(workdir):
    workdir = checked_path(workdir)
    if (workdir / 'hermes-watch.conf').exists():
        raise ValueError('Configuration already exists; use config-read')
    canonical = workdir / 'hermes-signed.ipa'
    candidates = [canonical] if canonical.is_file() else sorted(workdir.glob('*-signed.ipa'))
    if not candidates:
        raise ValueError('No signed IPA found')
    groups, records = set(), []
    for candidate in candidates:
        with zipfile.ZipFile(checked_path(candidate)) as archive:
            validate_zip(archive)
            root, _ = watch_info(archive)
            data = _watch_profile(archive, root)
            valid = set()
            for group in _profile_groups(data):
                try:
                    group_bytes(group)
                except ValueError:
                    continue
                valid.add(group)
            if not valid:
                raise ValueError('No valid 22-byte App Group in Watch profile')
            groups.update(valid)
            records.append((candidate, root))
    if len(groups) != 1:
        raise ValueError('Ambiguous App Groups in signed IPA profiles')
    group = groups.pop()
    signed, root = max(records, key=lambda item: (item[0].stat().st_mtime_ns, str(item[0])))
    grouped = workdir / 'hermes-grouped.ipa'
    alternatives = sorted(workdir.glob('*grouped.ipa'), key=lambda p: (p.stat().st_mtime_ns, str(p)), reverse=True)
    if not grouped.is_file():
        grouped = alternatives[0] if alternatives else None
    if grouped is not None:
        checked_path(grouped)
        try:
            verify_grouped(grouped, group)
        except (ValueError, KeyError, OSError, zipfile.BadZipFile):
            # An obsolete optional renewal source must not prevent upgrade/import.
            grouped = None
    return {'values': {'GROUP_ID': group, 'WATCH_UDID': '',
                       'APP_NAME': PurePosixPath(root).name, 'LAST_IPA_URL': '(manual)',
                       'SIGNED_IPA': str(signed.resolve()),
                       'GROUPED_IPA': str(grouped.resolve()) if grouped is not None else '',
                       'UPSTREAM_TAG': '', 'LAST_SUCCESS_AT': ''}}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    subs = parser.add_subparsers(dest='command', required=True)
    cmd = subs.add_parser('latest'); cmd.add_argument('destination')
    cmd = subs.add_parser('patch'); cmd.add_argument('source'); cmd.add_argument('destination'); cmd.add_argument('group')
    cmd = subs.add_parser('extract-watch'); cmd.add_argument('source'); cmd.add_argument('destination')
    cmd = subs.add_parser('profile'); cmd.add_argument('source')
    cmd = subs.add_parser('config-read'); cmd.add_argument('source')
    cmd = subs.add_parser('config-import'); cmd.add_argument('workdir')
    cmd = subs.add_parser('verify-signed'); cmd.add_argument('source'); cmd.add_argument('group'); cmd.add_argument('watchudid')
    cmd = subs.add_parser('verify-grouped'); cmd.add_argument('source'); cmd.add_argument('group')
    cmd = subs.add_parser('info'); cmd.add_argument('source')
    args = parser.parse_args()
    try:
        if args.command == 'latest': result = latest(args.destination)
        elif args.command == 'patch': result = patch(args.source, args.destination, args.group)
        elif args.command == 'extract-watch': result = extract_watch(args.source, args.destination)
        elif args.command == 'profile': result = profile(args.source)
        elif args.command == 'config-read': result = config_read(args.source)
        elif args.command == 'config-import': result = config_import(args.workdir)
        elif args.command == 'verify-signed': result = verify_signed(args.source, args.group, args.watchudid)
        elif args.command == 'verify-grouped': result = verify_grouped(args.source, args.group)
        else: result = info(args.source)
        print(result if isinstance(result, str) else json.dumps(result))
    except Exception as error:
        print('IPA operation failed: ' + str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
